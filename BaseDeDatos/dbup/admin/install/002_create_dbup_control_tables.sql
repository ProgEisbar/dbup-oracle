CREATE SEQUENCE &&DBUP_OWNER..DBUP_CHANGELOG_SEQ
  START WITH 1
  INCREMENT BY 1
  NOCACHE
  NOCYCLE;

CREATE TABLE &&DBUP_OWNER..DBUP_CHANGELOG (
  DDL_ID          NUMBER NOT NULL,
  JIRA_TICKET     VARCHAR2(40) NOT NULL,
  SCRIPT_NAME     VARCHAR2(255) NOT NULL,
  TARGET_SCHEMA   VARCHAR2(128) NOT NULL,
  ENVIRONMENT     VARCHAR2(20) NOT NULL,
  GIT_COMMIT_SHA  VARCHAR2(64),
  EXECUTED_AT     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  EXECUTED_BY     VARCHAR2(128) DEFAULT SYS_CONTEXT('USERENV', 'SESSION_USER') NOT NULL,
  SESSION_USER    VARCHAR2(128) DEFAULT SYS_CONTEXT('USERENV', 'SESSION_USER') NOT NULL,
  OS_USER         VARCHAR2(128) DEFAULT SYS_CONTEXT('USERENV', 'OS_USER'),
  HOST            VARCHAR2(255) DEFAULT SYS_CONTEXT('USERENV', 'HOST'),
  IP_ADDRESS      VARCHAR2(64) DEFAULT SYS_CONTEXT('USERENV', 'IP_ADDRESS'),
  MODULE          VARCHAR2(128) DEFAULT SYS_CONTEXT('USERENV', 'MODULE'),
  CLIENT_ID       VARCHAR2(128) DEFAULT SYS_CONTEXT('USERENV', 'CLIENT_IDENTIFIER'),
  STATUS          VARCHAR2(20) NOT NULL,
  ERROR_MESSAGE   VARCHAR2(4000),
  CONSTRAINT PK_DBUP_CHANGELOG PRIMARY KEY (DDL_ID),
  CONSTRAINT CK_DBUP_CHANGELOG_ENV CHECK (ENVIRONMENT IN ('DEV', 'QA', 'UAT', 'PROD')),
  CONSTRAINT CK_DBUP_CHANGELOG_STATUS CHECK (STATUS IN ('SUCCESS', 'FAILED')),
  CONSTRAINT CK_DBUP_CHANGELOG_SCHEMA CHECK (REGEXP_LIKE(TARGET_SCHEMA, '^(ENTIDAD|PARAM)[0-9]{3}$'))
);

CREATE OR REPLACE TRIGGER &&DBUP_OWNER..TRG_DBUP_CHANGELOG_BI
BEFORE INSERT ON &&DBUP_OWNER..DBUP_CHANGELOG
FOR EACH ROW
BEGIN
  IF :NEW.DDL_ID IS NULL THEN
    :NEW.DDL_ID := &&DBUP_OWNER..DBUP_CHANGELOG_SEQ.NEXTVAL;
  END IF;
END;
/

CREATE UNIQUE INDEX &&DBUP_OWNER..UX_DBUP_CHANGELOG_SUCCESS
  ON &&DBUP_OWNER..DBUP_CHANGELOG (
    CASE WHEN STATUS = 'SUCCESS' THEN SCRIPT_NAME END,
    CASE WHEN STATUS = 'SUCCESS' THEN ENVIRONMENT END
  );

CREATE INDEX &&DBUP_OWNER..IX_DBUP_CHANGELOG_TICKET
  ON &&DBUP_OWNER..DBUP_CHANGELOG (JIRA_TICKET);

CREATE INDEX &&DBUP_OWNER..IX_DBUP_CHANGELOG_SCHEMA_ENV
  ON &&DBUP_OWNER..DBUP_CHANGELOG (TARGET_SCHEMA, ENVIRONMENT);

CREATE TABLE &&DBUP_OWNER..DBUP_ALLOWED_CLIENTS (
  CLIENT_ID       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ENVIRONMENT     VARCHAR2(20) NOT NULL,
  IP_ADDRESS      VARCHAR2(64) NOT NULL,
  OS_USER         VARCHAR2(128) NOT NULL,
  HOST_NAME       VARCHAR2(255),
  CLIENT_PROGRAM_NAME VARCHAR2(128) DEFAULT '*' NOT NULL,
  DESCRIPTION     VARCHAR2(255),
  ENABLED         CHAR(1) DEFAULT 'Y' NOT NULL,
  CREATED_AT      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CREATED_BY      VARCHAR2(128) DEFAULT SYS_CONTEXT('USERENV', 'SESSION_USER') NOT NULL,
  CONSTRAINT CK_DBUP_ALLOWED_ENV CHECK (ENVIRONMENT IN ('DEV', 'QA', 'UAT', 'PROD')),
  CONSTRAINT CK_DBUP_ALLOWED_ENABLED CHECK (ENABLED IN ('Y', 'N')),
  CONSTRAINT UX_DBUP_ALLOWED_CLIENT UNIQUE (ENVIRONMENT, IP_ADDRESS, OS_USER, HOST_NAME, CLIENT_PROGRAM_NAME)
);

COMMENT ON TABLE &&DBUP_OWNER..DBUP_ALLOWED_CLIENTS IS
  'Whitelist de IPs, OS users, hosts y programas autorizados para conectarse con &&DBUP_USER.';

CREATE TABLE &&DBUP_OWNER..DBUP_LOGIN_AUDIT (
  LOGIN_ID        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  EVENT_AT        TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  SESSION_USER    VARCHAR2(128) DEFAULT SYS_CONTEXT('USERENV', 'SESSION_USER') NOT NULL,
  OS_USER         VARCHAR2(128) DEFAULT SYS_CONTEXT('USERENV', 'OS_USER'),
  HOST            VARCHAR2(255) DEFAULT SYS_CONTEXT('USERENV', 'HOST'),
  IP_ADDRESS      VARCHAR2(64) DEFAULT SYS_CONTEXT('USERENV', 'IP_ADDRESS'),
  MODULE          VARCHAR2(128) DEFAULT SYS_CONTEXT('USERENV', 'MODULE'),
  CLIENT_ID       VARCHAR2(128) DEFAULT SYS_CONTEXT('USERENV', 'CLIENT_IDENTIFIER'),
  ALLOWED         CHAR(1) NOT NULL,
  BLOCK_REASON    VARCHAR2(4000),
  CONSTRAINT CK_DBUP_LOGIN_ALLOWED CHECK (ALLOWED IN ('Y', 'N'))
);

COMMENT ON TABLE &&DBUP_OWNER..DBUP_LOGIN_AUDIT IS
  'Auditoria de intentos de conexion del usuario tecnico &&DBUP_USER.';

GRANT SELECT, INSERT ON &&DBUP_OWNER..DBUP_CHANGELOG TO &&DBUP_USER;
